async function main() {
  // 1. Проверяем наличие колонки SAP_CODE в LINES
  const cols = await query(
    `SELECT TRIM(r.RDB$FIELD_NAME) AS fname
       FROM RDB$RELATION_FIELDS r
      WHERE TRIM(r.RDB$RELATION_NAME) = 'LINES'`,
    []
  );
  const hasCol = cols.some(r => r.fname === 'SAP_CODE');

  if (!hasCol) {
    console.log('Добавляю колонку SAP_CODE VARCHAR(30) в LINES...');
    await execute('ALTER TABLE LINES ADD SAP_CODE VARCHAR(30)', []);
    console.log('  Колонка добавлена.');
  } else {
    console.log('Колонка SAP_CODE уже существует, пропускаем ALTER TABLE.');
  }

  // 2. Обновляем SAP_CODE по ID линии
  const entries = Object.entries(SAP_MAPPING);
  console.log(`\nЗаполняю SAP_CODE для ${entries.length} линий...`);

  let updated = 0;
  let skipped = 0;

  for (const [lineId, sapCode] of entries) {
    // Проверяем — может уже заполнен этой сессией (повторный запуск)
    const rows = await query(
      'SELECT TRIM(SAP_CODE) AS sap FROM LINES WHERE ID = ?',
      [Number(lineId)]
    );
    if (!rows.length) {
      console.warn(`  [WARN] Линия ID=${lineId} не найдена в базе`);
      skipped++;
      continue;
    }
    if (rows[0].sap === sapCode) {
      skipped++;
      continue; // уже актуальный
    }
    await execute(
      'UPDATE LINES SET SAP_CODE = ? WHERE ID = ?',
      [sapCode, Number(lineId)]
    );
    updated++;
  }

  console.log(`  Обновлено: ${updated}, уже актуальных: ${skipped}`);

  // 3. Синхронизируем server/seed/lines.json
  console.log('\nОбновляю server/seed/lines.json...');
  const seedLines = JSON.parse(fs.readFileSync(SEED_PATH, 'utf-8'));
  let seedUpdated = 0;
  for (const line of seedLines) {
    const sap = SAP_MAPPING[line.id] ?? null;
    if (line.sapCode !== sap) {
      line.sapCode = sap;
      seedUpdated++;
    }
  }
  fs.writeFileSync(SEED_PATH, JSON.stringify(seedLines, null, 2), 'utf-8');
  console.log(`  seed/lines.json: обновлено ${seedUpdated} записей`);

  console.log('\nГотово!');
  process.exit(0);
}

main().catch(err => {
  console.error('[FATAL]', err.message);
  process.exit(1);
});
